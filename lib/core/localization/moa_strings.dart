    final safe = seconds < 0 ? 0 : seconds;
    if (safe < 60) return t('duration_seconds', args: {'seconds': '$safe'});
    final minutes = safe ~/ 60;
    if (minutes < 60) {
      return t('duration_minutes', args: {'minutes': '$minutes'});
    }
    return t('duration_hours',
        args: {'hours': '${minutes ~/ 60}', 'minutes': '${minutes % 60}'});
  }

